const WEAK_TOKENS = new Set(["yakult", "minum", "botol", "hari", "tubuh"]); // bobot kecil

function normalizeText(input: string): string {
  let t = input.toLowerCase();
  t = t.replace(/[^a-z0-9\s]/g, " ");
  t = t
    .replace(/\bdi mana\b/g, "dimana")
    .replace(/\b(dmn|dmna|dimn|dmana|dimna)\b/g, "dimana")
    .replace(/\b(kadaluarsa|kadaluwarsa|kedaluarsa|kedaluwarsa|kdl|exp)\b/g, "kedaluwarsa")
    .replace(/\b(brp|berapaa)\b/g, "berapa")
    .replace(/\b(knp|kenapa|ngapa)\b/g, "mengapa")
    .replace(/\bbgmn\b|\bbagaimana\b/g, "bagaimana")
    .replace(/\bkrn\b/g, "karena")
    .replace(/\byg\b/g, "yang")
    .replace(/\bdiminum\b/g, "minum")
    .replace(/\bmengonsumsi\b|\bkonsumsi\b/g, "minum")
    .replace(/\bpabriknya\b/g, "pabrik")
    .replace(/\bletaknya\b/g, "letak")
    .replace(/\bmanfaatnya\b/g, "manfaat");
  return t.replace(/\s+/g, " ").trim();
}

function tokensOf(text: string): string[] {
  return normalizeText(text)
    .split(" ")
    .filter(w => w.length > 1 && !STOPWORDS.has(w));
}

function weightOf(w: string): number {
  return WEAK_TOKENS.has(w) ? 0.4 : 1;
}

function containsPhrase(haystackNorm: string, phraseNorm: string): boolean {
  if (!phraseNorm) return false;
  return (" " + haystackNorm + " ").includes(" " + phraseNorm + " ");
}

interface FaqIndexEntry {
  item: FaqItem;
  tokens: Set<string>;
  tokenWeight: number;
  keywords: string[]; // sudah dinormalisasi
}

let faqIndex: FaqIndexEntry[] | null = null;

function getFaqIndex(): FaqIndexEntry[] {
  if (faqIndex) return faqIndex;
  faqIndex = YAKULT_FAQ_ITEMS.map(item => {
    const qNorm = normalizeText(item.q);
    let kws = [...item.keywords];
    for (const ov of KEYWORD_OVERRIDES) {
      if (qNorm.includes(normalizeText(ov.qContains))) {
        kws = ov.replace ? [...ov.keywords] : [...kws, ...ov.keywords];
      }
    }
    const tokens = new Set(tokensOf(item.q));
    let tokenWeight = 0;
    tokens.forEach(t => (tokenWeight += weightOf(t)));
    return {
      item,
      tokens,
      tokenWeight,
      keywords: Array.from(new Set(kws.map(normalizeText).filter(Boolean)))
    };
  });
  return faqIndex;
}

export function findFaqAnswer(query: string): string | null {
  if (!query) return null;
  const qNorm = normalizeText(query);
  if (qNorm.length < 3) return null;

  const qTokens = Array.from(new Set(tokensOf(query)));
  if (qTokens.length === 0) return null;
  let qWeight = 0;
  qTokens.forEach(t => (qWeight += weightOf(t)));

  let best: { entry: FaqIndexEntry; score: number } | null = null;

  for (const entry of getFaqIndex()) {
    // a) Kata kunci frasa utuh (batas kata). Frasa lebih panjang = lebih spesifik = skor lebih tinggi.
    let kwScore = 0;
    for (const kw of entry.keywords) {
      if (containsPhrase(qNorm, kw)) kwScore += 2 + kw.split(" ").length;
    }

    // b) Kecocokan kata dengan teks pertanyaan FAQ
    let shared = 0;
    for (const t of qTokens) if (entry.tokens.has(t)) shared += weightOf(t);
    const qCov = qWeight > 0 ? shared / qWeight : 0; // seberapa banyak isi pertanyaan user tercakup
    const iCov = entry.tokenWeight > 0 ? shared / entry.tokenWeight : 0; // seberapa banyak isi FAQ tercakup
    const overlapScore = 2 * qCov * iCov * 6;

    // Tanpa kata kunci: wajib sebagian besar isi pertanyaan memang ada di FAQ tersebut
    if (kwScore === 0 && !(shared >= 1.4 && qCov >= 0.6)) continue;

    const score = kwScore + overlapScore;
    if (score >= 3.5 && (!best || score > best.score)) best = { entry, score };
  }

  return best ? best.entry.item.a : null;
}

